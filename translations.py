def get_locale():
    """Обирає мову: спершу з сесії, потім Accept-Language, інакше дефолт.
    Поза контекстом запиту (фонові job'и APScheduler) — завжди дефолт."""
    if has_request_context():
        lang = session.get("lang")
        if lang in TRANSLATIONS:
            return lang
        best = request.accept_languages.best_match(list(TRANSLATIONS.keys()))
        if best:
            return best
    return DEFAULT_LANGUAGE


def t(key, **kwargs):
    lang = get_locale()
    text = TRANSLATIONS.get(lang, {}).get(key)
    if text is None:
        text = TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text
